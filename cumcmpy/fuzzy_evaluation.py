# ==========================================
# 模糊综合评价法 (Fuzzy Comprehensive Evaluation)
# 示例：软件质量综合评价
# ==========================================
import numpy as np

def fuzzy_comprehensive_evaluation():
    # 1. 定义权重集 A (各指标权重)
    # 评价指标：[图形界面易用性, 分支可视化功能, 软件轻量化程度, 免费与开源性]
    A = np.array([0.3, 0.4, 0.2, 0.1])
    
    # 2. 定义模糊评价矩阵 R
    # 评语集：[优秀, 良好, 一般, 较差]
    # 每一行代表一个指标在各个评语上的隶属度（例如通过问卷调查得出的比例）
    R = np.array([
        [0.4, 0.4, 0.1, 0.1],  # u1: 图形界面易用性
        [0.5, 0.3, 0.2, 0.0],  # u2: 分支可视化功能
        [0.2, 0.5, 0.2, 0.1],  # u3: 软件轻量化程度
        [0.6, 0.2, 0.1, 0.1]   # u4: 免费与开源性
    ])
    
    # 3. 模糊合成运算
    # 使用最常用的“加权平均型 (M(•, +))”，即普通的矩阵乘法
    B = np.dot(A, R)
    
    print("-" * 40)
    print("模糊综合评价结果:")
    print(f"综合评价向量 B = {B}")
    
    # 4. 结果判定（最大隶属度原则）
    eval_levels = ["优秀", "良好", "一般", "较差"]
    max_index = np.argmax(B)
    
    print(f"最大隶属度为: {B[max_index]:.3f}")
    print(f"最终评价结论为: 该对象的综合评价等级为【{eval_levels[max_index]}】")
    print("-" * 40)

if __name__ == "__main__":
    fuzzy_comprehensive_evaluation()